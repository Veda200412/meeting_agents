CREATE TABLE IF NOT EXISTS public.runs (
  id uuid PRIMARY KEY,
  owner_id uuid,
  name varchar(200),
  status varchar(50) NOT NULL DEFAULT 'CREATED',
  current_source_version integer NOT NULL DEFAULT 1,
  current_plan_version integer,
  review_cycle_count integer NOT NULL DEFAULT 0,
  max_review_cycles integer NOT NULL DEFAULT 2,
  fault_injection varchar(50),
  error_message text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.source_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
  version integer NOT NULL,
  transcript text NOT NULL,
  company_rules text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (run_id, version)
);

CREATE TABLE IF NOT EXISTS public.facts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
  source_version integer NOT NULL,
  fact_id varchar(50) NOT NULL,
  fact_type varchar(50) NOT NULL,
  content text NOT NULL,
  evidence_quote text NOT NULL,
  source_location varchar(200) NOT NULL,
  confidence varchar(50) NOT NULL,
  owner varchar(200),
  deadline varchar(200),
  missing_fields jsonb NOT NULL DEFAULT '[]'::jsonb,
  notes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.user_corrections (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
  fact_id varchar(50) NOT NULL,
  field_name varchar(100) NOT NULL,
  original_value text,
  corrected_value text NOT NULL,
  correction_note text NOT NULL DEFAULT '',
  new_source_version integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.agent_executions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
  agent_type varchar(20) NOT NULL,
  step_id varchar(100) NOT NULL UNIQUE,
  attempt_number integer NOT NULL DEFAULT 1,
  status varchar(20) NOT NULL DEFAULT 'running',
  started_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  input_snapshot jsonb,
  output_snapshot jsonb,
  error_message text,
  source_version integer NOT NULL,
  plan_version integer
);

CREATE TABLE IF NOT EXISTS public.plan_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
  version integer NOT NULL,
  source_version integer NOT NULL,
  tasks jsonb NOT NULL DEFAULT '[]'::jsonb,
  supported_facts jsonb NOT NULL DEFAULT '[]'::jsonb,
  recommendations jsonb NOT NULL DEFAULT '[]'::jsonb,
  unresolved_questions jsonb NOT NULL DEFAULT '[]'::jsonb,
  dependency_graph jsonb NOT NULL DEFAULT '[]'::jsonb,
  change_summary jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (run_id, version)
);

CREATE TABLE IF NOT EXISTS public.review_results (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
  plan_version integer NOT NULL,
  source_version integer NOT NULL,
  outcome varchar(50) NOT NULL,
  findings jsonb NOT NULL DEFAULT '[]'::jsonb,
  summary text NOT NULL DEFAULT '',
  open_questions jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.workflow_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
  event_type varchar(50) NOT NULL,
  agent_type varchar(20),
  description text NOT NULL,
  version_info jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.handoff_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id uuid NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
  from_agent varchar(20) NOT NULL,
  to_agent varchar(20) NOT NULL,
  payload_summary text NOT NULL DEFAULT '',
  payload jsonb,
  source_version integer NOT NULL,
  plan_version integer,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_runs_owner_created
  ON public.runs (owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_source_run ON public.source_versions (run_id);
CREATE INDEX IF NOT EXISTS ix_fact_run_sv ON public.facts (run_id, source_version);
CREATE INDEX IF NOT EXISTS ix_agent_run ON public.agent_executions (run_id, agent_type);
CREATE INDEX IF NOT EXISTS ix_review_run_pv ON public.review_results (run_id, plan_version);
CREATE INDEX IF NOT EXISTS ix_event_run ON public.workflow_events (run_id);

